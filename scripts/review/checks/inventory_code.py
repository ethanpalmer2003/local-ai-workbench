BLOCKS = (ast.If, ast.For, ast.AsyncFor, ast.While, ast.With, ast.AsyncWith, ast.Try, ast.TryStar, ast.Match)


@dataclass(frozen=True)
class FunctionSize:
    path: str
    name: str
    line: int
    code_lines: int
    depth: int


def nesting(node: ast.AST, depth: int = 0) -> int:
    if isinstance(node, (*FUNCTIONS, ast.ClassDef, ast.Lambda)):
        return depth
    current = depth + int(isinstance(node, BLOCKS))
    if isinstance(node, (ast.ListComp, ast.SetComp, ast.DictComp, ast.GeneratorExp)):
        current += len(node.generators)
    result = current
    for field, value in ast.iter_fields(node):
        children = value if isinstance(value, list) else [value]
        for child in children:
            if not isinstance(child, ast.AST):
                continue
            # - An elif is an alternative at the same level, not a nested if.
            is_elif = (
                isinstance(node, ast.If)
                and field == "orelse"
                and isinstance(child, ast.If)
                and child.col_offset == node.col_offset
            )
            base = depth if is_elif else current
            result = max(result, nesting(child, base))
    return result


def code_line_numbers(source: str, tree: ast.Module) -> set[int]:
    ignored = set()
    for node in ast.walk(tree):
        if not isinstance(node, (ast.Module, *FUNCTIONS, ast.ClassDef)):
            continue
        body = getattr(node, "body", None)
        first = body[0] if isinstance(body, list) and body else None
        if isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant) and isinstance(first.value.value, str):
            ignored.update(range(first.lineno, (first.end_lineno or first.lineno) + 1))
    lines = set()
    for token in tokenize.generate_tokens(io.StringIO(source).readline):
        if token.type in (
            tokenize.COMMENT,
            tokenize.NL,
            tokenize.NEWLINE,
            tokenize.INDENT,
            tokenize.DEDENT,
            tokenize.ENDMARKER,
            tokenize.ENCODING,
        ):
            continue
        lines.update(range(token.start[0], token.end[0] + 1))
    return lines - ignored


def inspect_source(source: str, path: str) -> list[FunctionSize]:
    tree = ast.parse(source, filename=path)
    code_lines = code_line_numbers(source, tree)
    results = []
    for node in ast.walk(tree):
        if not isinstance(node, FUNCTIONS):
            continue
        own_lines = {line for line in code_lines if node.lineno <= line <= (node.end_lineno or node.lineno)}
        for child in ast.walk(node):
            if child is node or not isinstance(child, (*FUNCTIONS, ast.ClassDef)):
                continue
            for statement in child.body:
                own_lines.difference_update(range(statement.lineno, (statement.end_lineno or statement.lineno) + 1))
        count = len(own_lines)
        depth = max((nesting(child) for child in node.body), default=0)
        results.append(FunctionSize(path, node.name, node.lineno, count, depth))
    return results


def maintained_python(root: Path):
    for directory, folders, files in os.walk(root):
        parent = Path(directory)
        folders[:] = [name for name in folders if not _excluded(name) and not (parent == root and name == "tests")]
        for name in sorted(files):
            if name.endswith(".py"):
                yield parent / name


# - one record shape for a folder row and one for a source-file row, named once instead of repeated
FolderRecord = dict[str, int | str]
SourceFileRecord = dict[str, int | str]


class FolderInventory(NamedTuple):
    """The folder rows and the source-file rows, which the report and the checks both read."""

    folders: list[FolderRecord]
    source_files: list[SourceFileRecord]


class FolderEnds(NamedTuple):
    """Both ends of the folder rule, from one pass over the same rows."""

    single: list[FolderRecord]
    small: list[FolderRecord]
    crowded: list[FolderRecord]


def repository_inventory(root: Path) -> FolderInventory:
    folders: list[FolderRecord] = []
    source_files: list[SourceFileRecord] = []
    for directory, children, names in os.walk(root):
        parent = Path(directory)
        children[:] = sorted(name for name in children if not _excluded(name))
        visible_names = [name for name in names if name not in {"Thumbs.db", ".DS_Store"}]
        markdown_files = sum(Path(name).suffix.lower() == ".md" for name in visible_names)
        python_modules = sum(
            Path(name).suffix.lower() == ".py" and name.lower() != "__init__.py" for name in visible_names
        )
        folders.append(
            {
                "directory": "." if parent == root else parent.relative_to(root).as_posix(),
                "files": len(visible_names),
                "rule_files": len(visible_names) - sum(name == "__init__.py" for name in visible_names),
                "subdirectories": len(children),
                "items": len(visible_names) + len(children),
                "markdown_files": markdown_files,
                "python_modules": python_modules,
            }
        )
        for name in visible_names:
            path = parent / name
            if path.suffix.lower() not in {".py", ".md"}:
                continue
            try:
                line_count = len(path.read_text(encoding="utf-8-sig", errors="replace").splitlines())
            except OSError:
                continue
            source_files.append(
                {
                    "path": path.relative_to(root).as_posix(),
                    "type": path.suffix.lower().lstrip("."),
                    "lines": line_count,
                }
            )
    folders.sort(key=lambda item: str(item["directory"]).casefold())
    source_files.sort(key=lambda item: (-int(item["lines"]), str(item["path"]).casefold()))
    return FolderInventory(folders, source_files)


class TreeTotal(NamedTuple):
    """One measured tree: how many files and bytes it holds, and what kind of thing it is."""

    tree: str
    kind: str
    files: int
    bytes: int


def tree_totals(root: Path) -> tuple[int, int]:
    """File count and bytes under one tree, from one scandir pass that follows no links."""
    files = 0
    size = 0
    pending = [root]
    while pending:
        try:
            entries = list(os.scandir(pending.pop()))
        except OSError:
            continue
        for entry in entries:
            try:
                if entry.is_dir(follow_symlinks=False):
                    pending.append(Path(entry.path))
                elif entry.is_file(follow_symlinks=False):
                    files += 1
                    size += entry.stat(follow_symlinks=False).st_size
            except OSError:
                continue
    return files, size


def workspace_totals(root: Path) -> list[TreeTotal]:
    """Every top-level tree and loose root file, with the evidence trees split out of the source tree.

    The evidence trees sit inside `scripts`, so `scripts` is reported without them: a row that mixed 29,000
    run files into our source would hide both facts.
    """
    evidence = [
        TreeTotal(name, "run evidence", *tree_totals(root / name)) for name in EVIDENCE_TREES if (root / name).is_dir()
    ]
    totals = []
    for entry in sorted(root.iterdir()):
        if not entry.is_dir():
            continue
        files, size = tree_totals(entry)
        inside = [item for item in evidence if item.tree.startswith(f"{entry.name}/")]
        totals.append(
            TreeTotal(
                entry.name,
                TREE_KINDS.get(entry.name, "our source"),
                files - sum(item.files for item in inside),
                size - sum(item.bytes for item in inside),
            )
        )
    loose = [entry for entry in root.iterdir() if entry.is_file()]
    if loose:
        totals.append(TreeTotal("(root files)", "our source", len(loose), sum(entry.stat().st_size for entry in loose)))
    return totals + evidence


def workspace_report(totals: list[TreeTotal], tracked: int) -> list[str]:
    """Where the files and bytes of the whole workspace sit, in the order a reader looks for them."""
    total_files = sum(item.files for item in totals)
    total_bytes = sum(item.bytes for item in totals)
    lines = [
        "",
        "## Whole workspace",
        "",
        f"{tracked} tracked files. Every tree below holds {total_files:,} files and {total_bytes / GIB:,.0f} GB;",
        "the shares are of those totals, so the rows add up to the whole folder.",
        "",
        "| Tree | Holds | Files | Files % | GB | Bytes % |",
        "| --- | --- | ---: | ---: | ---: | ---: |",
    ]
    lines.extend(
        f"| {item.tree} | {item.kind} | {item.files:,} | {100 * item.files / total_files:.1f} | "
        f"{item.bytes / GIB:,.2f} | {100 * item.bytes / total_bytes:.1f} |"
        for item in sorted(totals, key=lambda row: (-row.files, row.tree))
    )
    lines.extend(
        (
            "",
            "GB is GiB, the figure Explorer reports. One scandir pass per tree follows no links, so a folder",
            "counted twice in the table is one that contains another row, and the evidence rows are already",
            "subtracted from `scripts`.",
        )
    )
    return lines


def section_group_prompts(root: Path) -> list[tuple[str, int]]:
    """Files whose section headers pass the prompt, which asks for a split when the file is next touched."""
    prompts: list[tuple[str, int]] = []
    for path in maintained_python(root):
        try:
            count = len(SECTION_HEADER.findall(path.read_text(encoding="utf-8-sig", errors="replace")))
        except OSError:
            continue
        if count > GROUP_PROMPT:
            prompts.append((path.relative_to(root).as_posix(), count))
    return sorted(prompts, key=lambda item: (-item[1], item[0]))


def group_prompt_report(prompts: list[tuple[str, int]]) -> list[str]:
    """Name the files over the prompt, with the reading that a group is a stage rather than a fault."""
    lines = [
        "",
        f"## Section groups (prompt at more than {GROUP_PROMPT})",
        "",
        f"{len(prompts)} file(s) carry more named sections than the prompt. A section header marks a stage, so",
        "these are prompts to split the next time the file is touched, not failures: a hard cap would only",
        "regroup the same stages.",
        "",
        "| File | Sections |",
        "| --- | ---: |",
    ]
    lines.extend(f"| {path} | {count} |" for path, count in prompts)
    return lines


