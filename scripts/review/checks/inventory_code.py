# - a folder is validated at both ends: below the minimum it is a merge candidate, above the maximum it
#   needs another level, and both counts read the same direct-item number from one pass
MIN_FOLDER_ITEMS = 3
MAX_FOLDER_ITEMS = 20
# - a Python file is validated at both ends too: past the warning it wants splitting, past the cap it fails
WARN_FILE_LINES = 600
MAX_FILE_LINES = 800
# - the files already over the cap when the rule landed, with the length that allowed them; growth fails
FILE_BASELINE = project_cfg.SCRIPTS_DIR / "review" / "lists" / "file-length-baseline.json"


def load_file_baseline() -> dict[str, int]:
    if not FILE_BASELINE.is_file():
        return {}
    return dict(json.loads(FILE_BASELINE.read_text(encoding="utf-8"))["files"])


def save_file_baseline(rows: list[dict[str, int | str]]) -> None:
    accepted = {str(row["path"]): int(row["lines"]) for row in rows if int(row["lines"]) > MAX_FILE_LINES}
    FILE_BASELINE.write_text(json.dumps({"files": dict(sorted(accepted.items()))}, indent=2) + "\n", encoding="utf-8")


# - function size is reported for context; the one gate is ruff's McCabe complexity
LARGEST_FUNCTIONS = 20
DEBT_DOC = project_cfg.SCRIPTS_DIR / "review" / "GENERATED-COMPLEXITY-DEBT.md"
DEBT_PREAMBLE = (
    "# McCabe debt",
    "",
    "Generated by `python -m scripts.review.checks.inventory_code --complexity-debt`; do not edit by hand.",
    "",
    "Functions above the gate of 10. Each carries `# noqa: C901`; delete the annotation when the function is split.",
    "",
    "| Complexity | Function |",
    "| ---: | --- |",
)
EXCLUDED = {".git", "state", "__pycache__", ".pytest_cache", ".ruff_cache"}


def _excluded(name: str) -> bool:
    """A cache, a generated tree or any virtual environment, including a renamed `.venv-old`."""
    return name in REVIEW_EXCLUDED or name.startswith(".venv")


REVIEW_EXCLUDED = EXCLUDED | {
    "graphify-out",
    "frameworks",
    "data",
    "trash",
    "output",
    "node_modules",
    "vendor",
    "dist",
    "build",
    ".mypy_cache",
    ".zed",
    "old",
    "retired",
}
FUNCTIONS = (ast.FunctionDef, ast.AsyncFunctionDef)
INLINE_NOQA = re.compile(r"#\s*noqa\b", re.IGNORECASE)
BLOCKS = (ast.If, ast.For, ast.AsyncFor, ast.While, ast.With, ast.AsyncWith, ast.Try, ast.TryStar, ast.Match)


@dataclass(frozen=True)
class FunctionSize:
    path: str
    name: str
    line: int
    code_lines: int
    depth: int


def nesting(node: ast.AST, depth: int = 0) -> int:
    if isinstance(node, (*FUNCTIONS, ast.ClassDef, ast.Lambda)):
        return depth
    current = depth + int(isinstance(node, BLOCKS))
    if isinstance(node, (ast.ListComp, ast.SetComp, ast.DictComp, ast.GeneratorExp)):
        current += len(node.generators)
    result = current
    for field, value in ast.iter_fields(node):
        children = value if isinstance(value, list) else [value]
        for child in children:
            if not isinstance(child, ast.AST):
                continue
            # - An elif is an alternative at the same level, not a nested if.
            is_elif = (
                isinstance(node, ast.If)
                and field == "orelse"
                and isinstance(child, ast.If)
                and child.col_offset == node.col_offset
            )
            base = depth if is_elif else current
            result = max(result, nesting(child, base))
    return result


def code_line_numbers(source: str, tree: ast.Module) -> set[int]:
    ignored = set()
    for node in ast.walk(tree):
        if not isinstance(node, (ast.Module, *FUNCTIONS, ast.ClassDef)):
            continue
        body = getattr(node, "body", None)
        first = body[0] if isinstance(body, list) and body else None
        if isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant) and isinstance(first.value.value, str):
            ignored.update(range(first.lineno, (first.end_lineno or first.lineno) + 1))
    lines = set()
    for token in tokenize.generate_tokens(io.StringIO(source).readline):
        if token.type in (
            tokenize.COMMENT,
            tokenize.NL,
            tokenize.NEWLINE,
            tokenize.INDENT,
            tokenize.DEDENT,
            tokenize.ENDMARKER,
            tokenize.ENCODING,
        ):
            continue
        lines.update(range(token.start[0], token.end[0] + 1))
    return lines - ignored


def inspect_source(source: str, path: str) -> list[FunctionSize]:
    tree = ast.parse(source, filename=path)
    code_lines = code_line_numbers(source, tree)
    results = []
    for node in ast.walk(tree):
        if not isinstance(node, FUNCTIONS):
            continue
        own_lines = {line for line in code_lines if node.lineno <= line <= (node.end_lineno or node.lineno)}
        for child in ast.walk(node):
            if child is node or not isinstance(child, (*FUNCTIONS, ast.ClassDef)):
                continue
            for statement in child.body:
                own_lines.difference_update(range(statement.lineno, (statement.end_lineno or statement.lineno) + 1))
        count = len(own_lines)
        depth = max((nesting(child) for child in node.body), default=0)
        results.append(FunctionSize(path, node.name, node.lineno, count, depth))
    return results


def maintained_python(root: Path):
    for directory, folders, files in os.walk(root):
        parent = Path(directory)
        folders[:] = [name for name in folders if not _excluded(name) and not (parent == root and name == "tests")]
        for name in sorted(files):
            if name.endswith(".py"):
                yield parent / name


# - one record shape for a folder row and one for a source-file row, named once instead of repeated
FolderRecord = dict[str, int | str]
SourceFileRecord = dict[str, int | str]


class FolderInventory(NamedTuple):
    """The folder rows and the source-file rows, which the report and the checks both read."""

    folders: list[FolderRecord]
    source_files: list[SourceFileRecord]


class FolderEnds(NamedTuple):
    """Both ends of the folder rule, from one pass over the same rows."""

    sparse: list[FolderRecord]
    small: list[FolderRecord]
    crowded: list[FolderRecord]


def repository_inventory(root: Path) -> FolderInventory:
    folders: list[FolderRecord] = []
    source_files: list[SourceFileRecord] = []
    for directory, children, names in os.walk(root):
        parent = Path(directory)
        children[:] = sorted(name for name in children if not _excluded(name))
        visible_names = [name for name in names if name not in {"Thumbs.db", ".DS_Store"}]
        markdown_files = sum(Path(name).suffix.lower() == ".md" for name in visible_names)
        python_modules = sum(
            Path(name).suffix.lower() == ".py" and name.lower() != "__init__.py" for name in visible_names
        )
        folders.append(
            {
                "directory": "." if parent == root else parent.relative_to(root).as_posix(),
                "files": len(visible_names),
                "subdirectories": len(children),
                "items": len(visible_names) + len(children),
                "markdown_files": markdown_files,
                "python_modules": python_modules,
            }
        )
        for name in visible_names:
            path = parent / name
            if path.suffix.lower() not in {".py", ".md"}:
                continue
            try:
                line_count = len(path.read_text(encoding="utf-8-sig", errors="replace").splitlines())
            except OSError:
                continue
            source_files.append(
                {
                    "path": path.relative_to(root).as_posix(),
                    "type": path.suffix.lower().lstrip("."),
                    "lines": line_count,
                }
            )
    folders.sort(key=lambda item: str(item["directory"]).casefold())
    source_files.sort(key=lambda item: (-int(item["lines"]), str(item["path"]).casefold()))
    return FolderInventory(folders, source_files)


def folder_inventory_report(
    folders: list[FolderRecord],
    sparse_folders: list[FolderRecord],
    small_folders: list[FolderRecord],
    crowded_folders: list[FolderRecord],
) -> list[str]:
    lines = [
        "",
        "## Folder contents",
        "",
        "| Folder | Files | Subdirectories | Total items | .md files | Python modules* |",
        "| --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    lines.extend(
        f"| {item['directory']} | {item['files']} | {item['subdirectories']} | {item['items']} | "
        f"{item['markdown_files']} | {item['python_modules']} |"
        for item in folders
    )
    lines.extend(
        (
            "",
            "*Python modules exclude `__init__.py`.*",
            "",
            f"## Folder rule: at most {MAX_FOLDER_ITEMS} direct files, fewer than {MIN_FOLDER_ITEMS + 1} is a candidate",
            "",
            "Counts are prompts at the low end and a gate at the high end: split a crowded folder by purpose; a",
            "small one stays when it carries an owner, a native layout or an output identity.",
            "",
            "### Over the cap (fails the gate)",
            "",
        )
    )
    lines.extend(f"- {item['directory']} ({item['items']} item(s))" for item in crowded_folders)
    if not crowded_folders:
        lines.append("None.")
    lines.extend(("", "### Empty or one-item folders", ""))
    lines.extend(f"- {item['directory']} ({item['items']} item(s))" for item in sparse_folders)
    if not sparse_folders:
        lines.append("None.")
    lines.extend(
        (
            "",
            f"### Merge candidates (2 to {MIN_FOLDER_ITEMS} direct files)",
            "",
            "Review whether these groups have a distinct owner before merging; low counts alone are not a violation.",
            "",
            "| Folder | Items | .md files | Python modules* |",
            "| --- | ---: | ---: | ---: |",
        )
    )
    lines.extend(
        f"| {item['directory']} | {item['items']} | {item['markdown_files']} | {item['python_modules']} |"
        for item in small_folders
    )
    if not small_folders:
        lines.append("| None | - | - | - |")
    return lines


def _suppression_section(suppressions: list[str]) -> list[str]:
    lines = [
        "",
        "## Inline suppressions",
        "",
        "Every suppression belongs in `pyproject.toml`; an inline annotation fails the gate.",
        "",
    ]
    return [*lines, *(f"- {item}" for item in suppressions)] if suppressions else [*lines, "None."]


def _dependency_section(counts: dict[str, int]) -> list[str]:
    if not counts:
        return []
    return [
        "",
        "## Dependencies",
        "",
        f"{counts['locked']} locked; {counts['installed']} installed; "
        f"{counts['leftovers']} leftovers; {counts['drift']} lock issues.",
    ]


def folder_validation(folders: list[FolderRecord]) -> FolderEnds:
    """Both ends of the folder rule: sparse, merge candidates, and over the cap."""
    sparse = [
        item
        for item in folders
        if int(item["files"]) <= 1 and not (str(item["directory"]).endswith("/patches") and int(item["files"]) == 1)
    ]
    small = [item for item in folders if 1 < int(item["files"]) <= MIN_FOLDER_ITEMS]
    crowded = [item for item in folders if int(item["files"]) > MAX_FOLDER_ITEMS]
    return FolderEnds(sparse, small, crowded)


class FileLengths(NamedTuple):
    """The file rule from one pass: over the cap and accepted, over the cap and new, and under watch."""

    over: list[SourceFileRecord]
    blocked: list[SourceFileRecord]
    long: list[SourceFileRecord]


def file_lengths(source_files: list[SourceFileRecord], baseline: dict[str, int]) -> FileLengths:
    """Both ends of the file rule, with the accepted over-cap files kept apart from new ones."""
    over = [item for item in source_files if int(item["lines"]) > MAX_FILE_LINES]
    blocked = [item for item in over if int(item["lines"]) > baseline.get(str(item["path"]), 0)]
    long = [item for item in source_files if WARN_FILE_LINES < int(item["lines"]) <= MAX_FILE_LINES]
    return FileLengths(over, blocked, long)


def file_length_report(lengths: FileLengths, baseline: dict[str, int]) -> list[str]:
    """The file rule's section: what fails, what is accepted debt, and what is only long."""
    accepted = [item for item in lengths.over if item not in lengths.blocked]
    lines = [
        "",
        f"## File rule: at most {MAX_FILE_LINES} lines, above {WARN_FILE_LINES} wants splitting",
        "",
        "### Over the cap (fails the gate)",
        "",
    ]
    lines.extend(f"- {item['path']} ({item['lines']} lines)" for item in lengths.blocked)
    if not lengths.blocked:
        lines.append("None.")
    lines.extend(("", f"### Accepted over the cap ({len(accepted)})", ""))
    lines.extend(
        f"- {item['path']} ({item['lines']} lines, accepted at {baseline.get(str(item['path']))})" for item in accepted
    )
    if not accepted:
        lines.append("None.")
    lines.extend(("", f"### Over {WARN_FILE_LINES} lines (split when next touched)", ""))
    lines.extend(f"- {item['path']} ({item['lines']} lines)" for item in lengths.long)
    if not lengths.long:
        lines.append("None.")
    return lines


def print_file_lengths(lengths: FileLengths) -> None:
    """The gate's lines for the file rule."""
    if lengths.blocked:
        print(f"[FAIL] {len(lengths.blocked)} file(s) over {MAX_FILE_LINES} lines; split them by purpose")
        for item in lengths.blocked:
            print(f"[FAIL] {item['path']}: {item['lines']} lines")
    accepted = len(lengths.over) - len(lengths.blocked)
    if accepted:
        print(f"[INFO] {accepted} file(s) over the cap were accepted in the baseline; split them next touch")
    if lengths.long:
        print(f"[INFO] {len(lengths.long)} file(s) over {WARN_FILE_LINES} lines; split when next touched")


def report(
    results: list[FunctionSize],
    files: int,
    folders: list[FolderRecord],
    source_files: list[SourceFileRecord],
    artifacts: Path,
    suppressions: list[str],
    dependencies: dict[str, int] | None = None,
) -> int:
    sparse_folders, small_folders, crowded_folders = folder_validation(folders)
    baseline = load_file_baseline()
    lengths = file_lengths(source_files, baseline)
    largest = sorted(results, key=lambda item: (-item.code_lines, -item.depth, item.path, item.line))[
        :LARGEST_FUNCTIONS
    ]
    payload = {
        "files": files,
        "functions": len(results),
        "largest_functions": [asdict(item) for item in largest],
        "folders": folders,
        "sparse_folders": sparse_folders,
        "small_folder_candidates": small_folders,
        "crowded_folders": crowded_folders,
        "files_over_cap": lengths.over,
        "files_to_split": lengths.blocked,
        "long_files": lengths.long,
        "source_file_lines": source_files,
        "inline_suppressions": suppressions,
        "dependencies": dependencies or {},
    }
    lines = [
        "# Repository code review",
        "",
        f"{len(folders)} folders; {len(source_files)} Python/Markdown files; {files} maintained Python files audited; "
        f"{len(results)} functions.",
        "",
        "Function size is context, not a gate: ruff's McCabe rule fails a function above 10. Code lines exclude",
        "blank/comment/docstring lines; multiline signatures/data count. Nested bodies are measured independently.",
        "The function audit excludes the tests tree; benchmarks and probes are included. File/folder inventory excludes",
        "third-party installs, model data, generated state, trash and caches. JavaScript/TypeScript line counts are not",
        "included.",
        "",
        "## Largest Python and Markdown files",
        "",
        "| File | Type | Lines |",
        "| --- | --- | ---: |",
    ]
    lines.extend(f"| {item['path']} | {item['type']} | {item['lines']} |" for item in source_files[:100])
    lines.extend(folder_inventory_report(folders, sparse_folders, small_folders, crowded_folders))
    lines.extend(file_length_report(lengths, baseline))
    lines.extend(
        (
            "",
            f"## Largest functions (top {LARGEST_FUNCTIONS})",
            "",
            "| File:line | Function | Code lines | Depth |",
            "| --- | --- | ---: | ---: |",
        )
    )
    lines.extend(f"| {item.path}:{item.line} | {item.name} | {item.code_lines} | {item.depth} |" for item in largest)
    lines.extend(_suppression_section(suppressions))
    lines.extend(_dependency_section(dependencies or {}))
    (artifacts / "review.json").write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    (artifacts / "review.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(folders)} folders, {len(source_files)} Python/Markdown files; {len(results)} functions")
    if suppressions:
        print(f"[FAIL] {len(suppressions)} inline suppression(s); move them into pyproject.toml")
        for item in suppressions[:10]:
            print(f"[FAIL] {item}")
    if crowded_folders:
        print(f"[FAIL] {len(crowded_folders)} folder(s) over {MAX_FOLDER_ITEMS} direct files; split them by purpose")
        for item in crowded_folders:
            print(f"[FAIL] {item['directory']}: {item['items']} items")
    print_file_lengths(lengths)
    if sparse_folders or small_folders:
        print(
            f"[INFO] {len(sparse_folders)} empty or one-item, {len(small_folders)} merge candidate(s) "
            f"at 2 to {MIN_FOLDER_ITEMS} items; see report."
        )
    print(f"Review report: {artifacts / 'review.md'}")
    return bool(suppressions or crowded_folders or lengths.blocked)


def _debt_row(item: dict[str, Any], root: Path) -> tuple[int, str, str]:
    match = re.search(r"`(.+)` is too complex \((\d+) >", str(item.get("message", "")))
    location = item.get("location") or {}
    path = Path(str(item.get("filename", ""))).relative_to(root).as_posix()
    if not match:
        return 0, f"{path}:{location.get('row', 0)}", "?"
    return int(match.group(2)), f"{path}:{location.get('row', 0)}", f"`{match.group(1)}`"


def complexity_debt(root: Path) -> int:
    """Rewrite the debt table from ruff's McCabe count with the grandfathering noqa ignored."""
    result = subprocess.run(
        [
            sys.executable,
            "-m",
            "ruff",
            "check",
            "--config",
            "pyproject.toml",
            "--select",
            "C90",
            "--ignore-noqa",
            "--output-format",
            "json",
            ".",
        ],
        cwd=root,
        capture_output=True,
        text=True,
        check=False,
    )
    rows = sorted(
        (_debt_row(item, root) for item in json.loads(result.stdout or "[]") if item.get("code") == "C901"),
        key=lambda row: (-row[0], row[1]),
    )
    lines = [*DEBT_PREAMBLE, *(f"| {score} | `{path}` {name} |" for score, path, name in rows)]
    if not rows:
        lines.append("| None | - |")
    lines.extend(("", f"Remaining: {len(rows)}."))
    DEBT_DOC.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return len(rows)


def python_sources(root: Path):
    """Every maintained Python file, tests included; generated evidence and vendors excluded."""
    for directory, folders, names in os.walk(root):
        parent = Path(directory)
        folders[:] = sorted(name for name in folders if not _excluded(name))
        for name in sorted(names):
            if name.endswith(".py"):
                yield parent / name


def _comment_lines(source: str):
    """(line number, comment text) for real comments; docstrings and string literals are prose, not suppressions."""
    try:
        for token in tokenize.generate_tokens(io.StringIO(source).readline):
            if token.type == tokenize.COMMENT:
                yield token.start[0], token.string
    except (tokenize.TokenError, IndentationError, SyntaxError):
        return


def suppression_issues(root: Path) -> list[str]:
    """Inline `# noqa` is banned: every suppression belongs in pyproject's per-file ignores."""
    issues = []
    for path in python_sources(root):
        try:
            source = path.read_text(encoding="utf-8-sig", errors="replace")
        except OSError:
            continue
        for number, comment in _comment_lines(source):
            if INLINE_NOQA.search(comment):
                issues.append(f"Inline suppression: {path.relative_to(project_cfg.BASE_DIR).as_posix()}:{number}")
    return issues


def main(dependencies: dict[str, int] | None = None) -> int:
    if "--accept-files" in sys.argv[1:]:
        _folders, source_files = repository_inventory(project_cfg.BASE_DIR)
        save_file_baseline(source_files)
        print(f"Accepted {len(load_file_baseline())} file(s) over {MAX_FILE_LINES} lines -> {FILE_BASELINE.name}")
        return 0
    if "--complexity-debt" in sys.argv[1:]:
        print(f"Complexity debt rows: {complexity_debt(project_cfg.BASE_DIR)} -> {DEBT_DOC.name}")
        return 0
    root = project_cfg.SCRIPTS_DIR
    files = list(maintained_python(root))
    results = [
        result
        for path in files
        for result in inspect_source(path.read_text(encoding="utf-8-sig"), path.relative_to(root).as_posix())
    ]
    folders, source_files = repository_inventory(project_cfg.BASE_DIR)
    suppressions = suppression_issues(root)
    artifacts = project_cfg.component("shared").generated_dir / "code_review" / str(time.time_ns())
    artifacts.mkdir(parents=True, exist_ok=False)
    status = report(results, len(files), folders, source_files, artifacts, suppressions, dependencies)
    return int(bool(suppressions) or status)


if __name__ == "__main__":
    raise SystemExit(main())
