"""Render declared language support for every speech checkpoint as one page.

Declared coverage only: a cell says a model lists the language, never that it transcribes it well.
"""

import argparse
from typing import Any

from scripts.config import models as model_cfg
from scripts.config import project_config as project_cfg
from scripts.config.models import model_languages
from scripts.launchers import launcher_config as cfg

OUTPUT = project_cfg.CONFIG_DIR / "notes" / "LANGUAGE-MATRIX.md"
HEADER = "| Model | Stage | " + " | ".join(cfg.PRACTICE_LANGUAGES) + " | Declared | Tiers |"
HEADER_RULE = "| --- | --- | " + " | ".join(":-:" for _ in cfg.PRACTICE_LANGUAGES) + " | ---: | --- |"


def _codes(entry) -> set[str]:
    """Every language and locale base code a checkpoint lists."""
    listed = [*(entry["languages"] or []), *entry["locales"]]
    return {model_languages.normalized(code).split("-")[0] for code in listed}


def _stage(entry) -> str:
    return "+".join(task for task in ("asr", "tts") if task in entry["tasks"])


def _tiers(entry) -> str:
    tiers = entry.get("coverage_tiers") or {}
    if not tiers:
        return "declared"
    return ", ".join(f"{tier} {len(codes)}" for tier, codes in tiers.items())


def rows(catalog) -> list[dict[str, Any]]:
    """One row per speech checkpoint, practice languages marked from its declared codes."""
    rendered = []
    for entry in catalog["models"]:
        if not set(entry["tasks"]) & {"asr", "tts"}:
            continue
        codes = _codes(entry)
        unknown = entry["languages"] is None
        rendered.append(
            {
                "name": entry["name"],
                "stage": _stage(entry),
                "cells": {
                    code: ("" if unknown else ("yes" if code in codes else "")) for code in cfg.PRACTICE_LANGUAGES
                },
                "declared": "unknown" if unknown else len(entry["languages"]),
                "tiers": _tiers(entry),
            }
        )
    return rendered


def render(catalog) -> str:
    rendered = rows(catalog)
    missing = [row["name"] for row in rendered if row["declared"] == "unknown"]
    lines = [
        "# Language matrix",
        "",
        "Generated by `python -m scripts.tools.language_matrix`; do not edit by hand.",
        "Declared support only, from `model_languages.json`: a mark means the checkpoint lists that",
        "language, not that it transcribes or speaks it well. Accuracy for a listed language is the",
        "open question, and no per-language measurement exists.",
        "",
        HEADER,
        HEADER_RULE,
    ]
    for row in rendered:
        cells = " | ".join(str(row["cells"][code]) for code in cfg.PRACTICE_LANGUAGES)
        lines.append(f"| {row['name']} | {row['stage']} | {cells} | {row['declared']} | {row['tiers']} |")
    lines += [
        "",
        f"{len(rendered)} speech checkpoints; practice languages are " + ", ".join(cfg.PRACTICE_LANGUAGES) + ".",
        "`Declared` counts listed languages; `Tiers` names coverage tiers where a checkpoint publishes them.",
        "Unknown: " + (", ".join(missing) if missing else "none") + ".",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Report a stale page and exit non-zero")
    args = parser.parse_args(argv)
    text = render(model_languages.read_catalog())
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        if current != text:
            print(f"[FAIL] {OUTPUT.name} is stale; run scripts.tools.language_matrix")
            return 1
        print(f"[OK] {OUTPUT.name} matches its source")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    catalog = model_languages.read_catalog()
    print(f"[OK] {OUTPUT.relative_to(project_cfg.BASE_DIR)}")
    print(f"{len(rows(catalog))} speech checkpoints, {len(model_cfg.models_for('asr'))} ASR weights")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
