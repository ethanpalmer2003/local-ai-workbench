"""Capability matrix rows, freshness marks and headline extraction; no run evidence is created."""

import contextlib
import io
import subprocess
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

from scripts.benchmarks.shared import language_corpus
from scripts.tools import capability_matrix as matrix


def fake_git(command, **_kwargs):
    """A clean checkout at a fixed commit; git itself never starts in the model-free suite."""
    if "--show-toplevel" in command:
        return subprocess.CompletedProcess(command, 0, stdout=f"{command[2]}\n")
    output = f"{'a' * 40}\n" if "rev-parse" in command else ""
    return subprocess.CompletedProcess(command, 0, stdout=output)


def provenanced(models: list[dict[str, object]] | None = None) -> dict[str, object]:
    """A recorded block that matches this workspace except where a test says otherwise."""
    return {
        "recorded_at": "2026-01-02T03:04:05+00:00",
        "frameworks": [],
        "models": models or [],
        "corpus": language_corpus.identity(),
    }


class FreshnessTests(unittest.TestCase):
    def test_a_capability_without_evidence_is_never_run(self):
        self.assertEqual(matrix.freshness(None), "never run")

    def test_a_run_that_recorded_no_provenance_cannot_be_checked(self):
        self.assertEqual(matrix.freshness({"status": "completed"}), "[WARN] unprovenanced")

    def test_a_run_that_did_not_complete_is_not_current(self):
        for status in ("incomplete", "failed", "unreviewed"):
            self.assertEqual(matrix.freshness({"status": status}), f"[WARN] last run {status}")

    def test_a_passed_run_is_treated_as_completed(self):
        self.assertEqual(matrix.freshness({"status": "passed"}), "[WARN] unprovenanced")

    def test_matching_provenance_is_current(self):
        with tempfile.TemporaryDirectory() as folder:
            weight = Path(folder) / "model.gguf"
            weight.write_bytes(b"weights")
            block = provenanced()
            block["models"] = [matrix.provenance.file_identity("chat", weight)]
            self.assertEqual(matrix.freshness({"provenance": block}), "[OK]")

    def test_a_replaced_weight_makes_the_row_stale_and_names_it(self):
        with tempfile.TemporaryDirectory() as folder:
            weight = Path(folder) / "model.gguf"
            weight.write_bytes(b"weights")
            recorded = matrix.provenance.file_identity("chat", weight)
            weight.write_bytes(b"replaced weights")
            block = provenanced([recorded])
            self.assertEqual(matrix.freshness({"provenance": block}), "[WARN] stale: chat changed")

    def test_a_moved_framework_makes_the_row_stale(self):
        block = provenanced()
        block["frameworks"] = [{"key": "llamacpp", "commit": "0" * 40}]
        with patch.object(matrix.provenance.subprocess, "run", side_effect=fake_git):
            self.assertEqual(matrix.freshness({"provenance": block}), "[WARN] stale: llamacpp moved")

    def test_a_changed_corpus_manifest_makes_the_row_stale(self):
        block = provenanced()
        block["corpus"] = {**language_corpus.identity(), "manifest_sha256": "0" * 64}
        self.assertIn("corpus manifest changed", matrix.freshness({"provenance": block}))


class HeadlineTests(unittest.TestCase):
    def test_a_language_run_shows_chat_ttft_per_backend(self):
        report = {
            "results": [
                {
                    "backend": "practice",
                    "legs": {"chat": {"status": "measured", "requests": [{"first_token_seconds": 1.0, "chunks": 4}]}},
                },
                {
                    "backend": "lemonade",
                    "legs": {"chat": {"status": "measured", "requests": [{"first_token_seconds": 0.5, "chunks": 4}]}},
                },
            ]
        }
        self.assertEqual(matrix._headline(report), "practice TTFT 1.00 s; lemonade TTFT 0.50 s")

    def test_a_recognition_report_shows_its_pooled_wer(self):
        self.assertEqual(matrix._headline({"summary": {"pooled_wer": 0.125}}), "WER 12.5%")

    def test_a_report_without_numbers_shows_none_rather_than_zero(self):
        self.assertEqual(matrix._headline({"status": "completed"}), "-")
        self.assertEqual(matrix._headline(None), "-")


class RenderTests(unittest.TestCase):
    def test_every_registered_capability_gets_one_row(self):
        with patch.object(matrix.provenance.subprocess, "run", side_effect=fake_git):
            text = matrix.render(matrix.rows())
        self.assertIn("Generated by `python -m scripts.tools.capability_matrix`", text)
        self.assertIn("| Work | Category | Last run | Status | Result | Freshness | Evidence |", text)
        for _, label in matrix.CAPABILITIES:
            self.assertIn(f"| {label} |", text)

    def test_a_row_keeps_its_numbers_and_links_its_evidence(self):
        row = matrix.Row("Work", "subject", None, None)
        text = matrix.render([row])
        self.assertIn("| Work | probe | - | - | - | never run | - |", text)

    def test_parked_work_is_marked_and_explained(self):
        row = matrix.Row("Drama offload screen", "shared/drama3_offload", None, None)
        text = matrix.render([row])
        self.assertIn("| Drama offload screen | benchmark | - | - | - | [defer] | - |", text)
        self.assertIn("Deferred, no rerun planned: Drama offload screen (", text)

    def test_parked_work_is_not_counted_as_a_rerun(self):
        row = matrix.Row("Drama offload screen", "shared/drama3_offload", None, None)
        printed = io.StringIO()
        with patch.object(matrix, "rows", return_value=[row]), contextlib.redirect_stdout(printed):
            self.assertEqual(matrix.main(["--check"]), 0)
        self.assertIn("1 capabilities, 0 needing a rerun, 1 deferred", printed.getvalue())


if __name__ == "__main__":
    unittest.main()
